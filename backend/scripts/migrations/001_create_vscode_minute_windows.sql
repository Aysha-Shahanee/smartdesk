CREATE TABLE IF NOT EXISTS vscode_minute_windows (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id TEXT NOT NULL,
    window_start TEXT NOT NULL,
    window_end TEXT NOT NULL,
    timezone TEXT,
    workspace_name TEXT,
    project_path TEXT,
    repo_id TEXT,
    git_branch TEXT,
    active_file_path TEXT,
    active_file_name TEXT,
    active_language TEXT,
    vscode_foreground_sec INTEGER,
    active_editor_sec INTEGER,
    idle_sec INTEGER,
    edit_count INTEGER NOT NULL DEFAULT 0,
    save_count INTEGER NOT NULL DEFAULT 0,
    file_switch_count INTEGER NOT NULL DEFAULT 0,
    terminal_command_count INTEGER NOT NULL DEFAULT 0,
    debug_run_count INTEGER NOT NULL DEFAULT 0,
    source TEXT,
    schema_version TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE(user_id, window_start, window_end)
);
