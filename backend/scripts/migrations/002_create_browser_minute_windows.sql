CREATE TABLE IF NOT EXISTS browser_minute_windows (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id TEXT NOT NULL,
    window_start TEXT NOT NULL,
    window_end TEXT NOT NULL,
    timezone TEXT,
    browser_name TEXT,
    active_tab_domain TEXT,
    active_tab_url TEXT,
    active_tab_title TEXT,
    active_tab_category TEXT,
    browser_active_time_sec INTEGER,
    browser_idle_time_sec INTEGER,
    productive_time_sec INTEGER,
    neutral_time_sec INTEGER,
    distracting_time_sec INTEGER,
    communication_time_sec INTEGER,
    tab_switch_count INTEGER NOT NULL DEFAULT 0,
    unique_domains_count INTEGER NOT NULL DEFAULT 0,
    source TEXT,
    schema_version TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE(user_id, window_start, window_end)
);
